Result<std::unique_ptr<BitmapFont>> BitmapFont::create(Renderer &renderer) {
    std::vector<Color> pixels(static_cast<std::size_t>(columns * cell * 6 * cell),
                              Color{0, 0, 0, 0});
    for (int index = 0; index < glyphCount; ++index) {
        const int originX = (index % columns) * cell, originY = (index / columns) * cell;
        for (int row = 0; row < glyphHeight; ++row)
            for (int column = 0; column < glyphWidth; ++column)
                if (glyphs[static_cast<std::size_t>(index)].rows[row][column] == '#')
                    pixels[static_cast<std::size_t>((originY + row) * columns * cell + originX +
                                                    column)] = {255, 255, 255, 255};
    }
    auto texture = renderer.createTexture(columns * cell, 6 * cell, pixels);
    if (!texture)
        return Error{"Create font atlas: " + texture.error()};
    auto font = std::unique_ptr<BitmapFont>(new BitmapFont());
    font->atlas_ = texture.value();
    return font;
}

Vec2 BitmapFont::measure(std::string_view text, float scale) {
    int lines = 1, longest = 0, current = 0;
    for (const char c : text) {
        if (c == '\n') {
            ++lines;
            current = 0;
        } else if ((static_cast<unsigned char>(c) & 0xC0) !=
                   0x80) { // Count code points, not bytes.
            longest = std::max(longest, ++current);
        }
    }
    if (text.empty())
        return {};
    return {static_cast<float>(longest * advance - 1) * scale,
            static_cast<float>(lines * lineAdvance - 2) * scale};
}

Status BitmapFont::draw(Renderer &renderer, std::string_view text, Vec2 topLeft, float scale,
                        Color color, int layer, float depth) const {
    if (!(scale > 0.0F) || !std::isfinite(scale) || !finite(topLeft))
        return Error{"Invalid text position or scale"};
    Vec2 pen = topLeft;
    for (const char c : text) {
        const auto byte = static_cast<unsigned char>(c);
        if (c == '\n') {
            pen = {topLeft.x, pen.y + static_cast<float>(lineAdvance) * scale};
            continue;
        }
        if ((byte & 0xC0) == 0x80)
            continue; // Continuation byte of a multi-byte character already drawn as '?'.
        const int index = glyphIndex(byte);
        if (index != 0) { // Spaces only advance the pen.
            Sprite sprite;
            sprite.texture = atlas_;
            sprite.transform.position = pen;
            sprite.size = {static_cast<float>(glyphWidth) * scale,
                           static_cast<float>(glyphHeight) * scale};
            sprite.anchor = {0.0F, 0.0F};
            sprite.tint = color;
            sprite.source = Rect{{static_cast<float>((index % columns) * cell),
                                  static_cast<float>((index / columns) * cell)},
                                 {static_cast<float>(glyphWidth), static_cast<float>(glyphHeight)}};
            sprite.layer = layer;
            sprite.depth = depth;
            if (auto submitted = renderer.submit(sprite); !submitted)
                return submitted;
        }
        pen.x += static_cast<float>(advance) * scale;
    }
    return success();
}
